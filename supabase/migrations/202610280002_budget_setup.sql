begin;

alter table public.profiles
  add column currency text not null default 'USD'
    check (currency in ('USD', 'CAD', 'EUR', 'GBP', 'AUD', 'NZD')),
  add column time_zone text not null default 'UTC';

grant update (currency, time_zone) on public.profiles to authenticated;
create policy "Update own preferences" on public.profiles
  for update to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid() references public.profiles(id),
  name text not null check (name = btrim(name) and char_length(name) between 1 and 60),
  display_order bigint generated by default as identity,
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  unique (id, owner_id)
);

-- Retain names for archived categories so restoring cannot create duplicates.
create unique index categories_owner_name on public.categories (owner_id, lower(name));
create index categories_owner_order on public.categories (owner_id, display_order, id);

create table public.monthly_limits (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid() references public.profiles(id),
  category_id uuid not null,
  month date not null check (
    extract(day from month) = 1 and month between date '1900-01-01' and date '9999-12-01'
  ),
  amount_cents bigint not null check (amount_cents between 0 and 99999999999),
  unique (category_id, month),
  foreign key (category_id, owner_id) references public.categories(id, owner_id)
    on delete restrict
);
create index monthly_limits_owner_month on public.monthly_limits (owner_id, month);

alter table public.categories enable row level security;
alter table public.monthly_limits enable row level security;
revoke all on public.categories, public.monthly_limits from anon, authenticated;
grant select, insert, update, delete on public.categories, public.monthly_limits to authenticated;
grant usage on sequence public.categories_display_order_seq to authenticated;

create policy "Own categories" on public.categories for all to authenticated
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);
create policy "Own limits" on public.monthly_limits for all to authenticated
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);

create function public.check_budget_preferences()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  if not exists (select 1 from pg_catalog.pg_timezone_names where name = new.time_zone) then
    raise exception 'Invalid timezone' using errcode = '23514';
  end if;
  if new.currency <> old.currency and exists (
    select 1 from public.monthly_limits where owner_id = new.id
  ) then
    raise exception 'Currency cannot change while monthly limits exist' using errcode = '23514';
  end if;
  return new;
end;
$$;
create trigger check_budget_preferences before update on public.profiles
  for each row execute function public.check_budget_preferences();

-- Serialize limit writes against preference changes, preventing a currency
-- change racing the first limit insert. Historical limits may still be edited
-- for archived categories, but new limits cannot be created for them.
create function public.check_limit_category()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  perform 1 from public.profiles where id = new.owner_id for share;
  if tg_op = 'INSERT' or new.category_id <> old.category_id or new.month <> old.month then
    perform 1 from public.categories
      where id = new.category_id and owner_id = new.owner_id and archived_at is null
      for share;
    if not found then
      raise exception 'Choose an active category' using errcode = '23514';
    end if;
  end if;
  return new;
end;
$$;
create trigger check_limit_category before insert or update on public.monthly_limits
  for each row execute function public.check_limit_category();

-- Invoker functions obey the same RLS as normal requests.
create function public.move_category(category uuid, direction integer)
returns void language plpgsql security invoker set search_path = '' as $$
declare
  ids uuid[];
  position integer;
  target integer;
  neighbor uuid;
begin
  if auth.uid() is null or direction not in (-1, 1) or direction is null then
    raise exception 'Invalid move' using errcode = '22023';
  end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(auth.uid()::text, 0));
  select array_agg(id order by display_order, id) into ids
    from public.categories where owner_id = auth.uid() and archived_at is null;
  position := array_position(ids, category);
  if position is null then
    raise exception 'Category not found' using errcode = '22023';
  end if;
  target := position + direction;
  if target < 1 or target > array_length(ids, 1) then return; end if;
  neighbor := ids[target];
  ids[target] := category;
  ids[position] := neighbor;
  update public.categories c set display_order = ordered.ordinality
    from unnest(ids) with ordinality as ordered(id, ordinality)
    where c.id = ordered.id and c.owner_id = auth.uid();
end;
$$;

create function public.copy_previous_limits(target_month date)
returns integer language plpgsql security invoker set search_path = '' as $$
declare copied integer;
begin
  if auth.uid() is null or target_month is null
    or extract(day from target_month) <> 1
    or target_month not between date '1900-01-01' and date '9999-12-01' then
    raise exception 'Invalid month' using errcode = '22023';
  end if;
  insert into public.monthly_limits (owner_id, category_id, month, amount_cents)
    select l.owner_id, l.category_id, target_month, l.amount_cents
    from public.monthly_limits l
    join public.categories c on c.id = l.category_id and c.owner_id = l.owner_id
    where l.owner_id = auth.uid() and c.archived_at is null
      and l.month = (target_month - interval '1 month')::date
    on conflict (category_id, month) do nothing;
  get diagnostics copied = row_count;
  return copied;
end;
$$;

revoke all on function public.check_budget_preferences(), public.check_limit_category(),
  public.move_category(uuid, integer), public.copy_previous_limits(date) from public, anon;
grant execute on function public.move_category(uuid, integer), public.copy_previous_limits(date)
  to authenticated;

commit;
